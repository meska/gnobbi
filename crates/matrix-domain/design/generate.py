#!/usr/bin/env python3
"""Generate Rust, Swift and Kotlin constants from design/tokens.toml (Python >= 3.11).
Run from anywhere: python3 crates/matrix-domain/design/generate.py"""
import pathlib, tomllib

here = pathlib.Path(__file__).resolve().parent
src = tomllib.loads((here / "tokens.toml").read_text(encoding="utf-8"))
THEME_ORDER = ["classic", "day", "dark", "night"]
COLORS = ["surface", "text", "secondary", "placeholder", "accent", "timeline", "outgoing", "selected",
          "border", "input", "disabled", "selection", "mention_row", "error", "on_accent", "avatar_text"]
assert list(src["themes"]) == THEME_ORDER, "themes must be classic, day, dark, night"
for t in src["themes"].values():
    assert set(t) == {"label", "dark", *COLORS}, "theme keys differ from the colour list"

def camel(s):
    h, *r = s.split("_")
    return h + "".join(x.title() for x in r)

def hexv(s):
    return s.lower()

def rust():
    o = ["// @generated by design/generate.py from design/tokens.toml. Do not edit.", "",
         "#[derive(Clone, Copy, Debug, PartialEq, Eq)]", "pub struct Palette {"]
    o += [f"    pub {c}: u32," for c in COLORS] + ["}", "",
         "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
         "pub struct ThemeTokens {", "    pub id: &'static str,", "    pub label: &'static str,",
         "    pub dark: bool,", "    pub palette: Palette,", "}", "",
         "/// Logical px.", "pub struct Layout {"]
    o += [f"    pub {k}: f32," for k in src["layout"]] + ["}", "",
          "pub const LAYOUT: Layout = Layout {"]
    o += [f"    {k}: {v}.," for k, v in src["layout"].items()] + ["};", ""]
    o += [f"pub const SPACING_{k.upper()}: f32 = {v}.;" for k, v in src["spacing"].items()]
    o += [f"pub const {k.upper()}: u32 = {hexv(v)};" for k, v in src["constants"].items()]
    o += [f'pub const {k.upper()}: &str = "{v}";' for k, v in src["strings"].items()]
    o += ["", "/// Classic, Day, Dark, Night.", "pub const THEMES: [ThemeTokens; 4] = ["]
    for n in THEME_ORDER:
        t = src["themes"][n]
        o += ["    ThemeTokens {", f'        id: "{n}",', f'        label: "{t["label"]}",',
              f'        dark: {str(t["dark"]).lower()},', "        palette: Palette {"]
        o += [f"            {c}: {hexv(t[c])}," for c in COLORS] + ["        },", "    },"]
    o.append("];")
    return "\n".join(o) + "\n"

def swift():
    o = ["// @generated by design/generate.py from design/tokens.toml. Do not edit.", "",
         "enum DesignTokens {"]
    o += [f"    static let {camel('layout_' + k)}: Double = {v}" for k, v in src["layout"].items()]
    o += [f"    static let {camel('spacing_' + k)}: Double = {v}" for k, v in src["spacing"].items()]
    o += [f"    static let {camel(k)}: UInt32 = {hexv(v)}" for k, v in src["constants"].items()]
    o += [f'    static let {camel(k)} = "{v}"' for k, v in src["strings"].items()]
    o.append("")
    for n in THEME_ORDER:
        t = src["themes"][n]
        o += [f"    enum {n.title()} {{", f'        static let label = "{t["label"]}"',
              f"        static let dark = {str(t['dark']).lower()}"]
        o += [f"        static let {camel(c)}: UInt32 = {hexv(t[c])}" for c in COLORS] + ["    }"]
    o.append("}")
    return "\n".join(o) + "\n"

def kotlin():
    o = ["// @generated by design/generate.py from design/tokens.toml. Do not edit.", "",
         "package chat.gnobbi.design", "", "object DesignTokens {"]
    o += [f"    const val LAYOUT_{k.upper()} = {v}.0" for k, v in src["layout"].items()]
    o += [f"    const val SPACING_{k.upper()} = {v}.0" for k, v in src["spacing"].items()]
    # Kotlin hex literals above Int.MAX need the L suffix.
    o += [f"    const val {k.upper()} = {hexv(v)}L" for k, v in src["constants"].items()]
    o += [f'    const val {k.upper()} = "{v}"' for k, v in src["strings"].items()]
    o.append("")
    for n in THEME_ORDER:
        t = src["themes"][n]
        o += [f"    object {n.title()} {{", f'        const val LABEL = "{t["label"]}"',
              f"        const val DARK = {str(t['dark']).lower()}"]
        o += [f"        const val {c.upper()} = {hexv(t[c])}L" for c in COLORS] + ["    }"]
    o.append("}")
    return "\n".join(o) + "\n"

for path, text in [(here.parent / "src" / "design.rs", rust()),
                   (here / "generated" / "DesignTokens.swift", swift()),
                   (here / "generated" / "DesignTokens.kt", kotlin())]:
    path.write_text(text, encoding="utf-8")
